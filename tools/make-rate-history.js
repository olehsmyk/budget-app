// Generates docs/nbu-history.js: official NBU rates for past dates, so old months work offline and at
// once. A browser can't do this itself, because the NBU's date-range service blocks web pages.
//
// Run from budget-app: node tools/make-rate-history.js [start date, default 2021-01-01]
import { writeFileSync } from 'node:fs';

const CODES = ['USD', 'EUR', 'GBP', 'PLN', 'IDR', 'CZK', 'CHF', 'SEK', 'NOK', 'DKK', 'CAD', 'AUD', 'JPY'];
const DAY_MS = 86400000;

const start = process.argv[2] || '2021-01-01';
const end = new Date().toISOString().slice(0, 10);
const compact = (iso) => iso.replaceAll('-', '');
const dayIndex = (iso) => (Date.parse(`${iso}T00:00:00Z`) - Date.parse(`${start}T00:00:00Z`)) / DAY_MS;
const days = dayIndex(end) + 1;

async function fetchRates(code) {
  const url = `https://bank.gov.ua/NBU_Exchange/exchange_site?start=${compact(start)}&end=${compact(end)}&valcode=${code.toLowerCase()}&sort=exchangedate&order=asc&json`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${code}: HTTP ${response.status}`);
  const rows = await response.json();
  const rates = new Array(days).fill(null);
  for (const row of rows) {
    const [d, m, y] = row.exchangedate.split('.');
    const i = dayIndex(`${y}-${m}-${d}`);
    // Some currencies are quoted per 10 or 100 units here, so this is the only safe field.
    if (i >= 0 && i < days) rates[i] = row.rate_per_unit;
  }
  // A date the NBU left out keeps the rate before it, as weekends do in its own data.
  for (let i = 1; i < days; i++) rates[i] ??= rates[i - 1];
  return rates;
}

const rates = {};
for (const code of CODES) {
  rates[code] = await fetchRates(code);
  console.log(code, rates[code].filter((r) => r !== null).length, 'of', days);
}

writeFileSync(
  'docs/nbu-history.js',
  `// Generated by tools/make-rate-history.js. Do not edit by hand.
// Official exchange rates of the National Bank of Ukraine, in UAH for 1 unit, one for each day from
// \`start\`. Source: https://bank.gov.ua/ua/open-data
export const NBU_HISTORY = ${JSON.stringify({ start, rates })};
`,
);

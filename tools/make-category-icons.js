// Generates docs/category-icons.js from a local copy of the lucide-static npm package, so the app
// ships only the icons it offers and never needs the network to draw them.
//
// Run from budget-app: node tools/make-category-icons.js <path to the extracted package>
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const NAMES = [
  'shopping-cart', 'utensils', 'coffee', 'pizza', 'apple', 'beer', 'wine',
  'bus', 'car', 'fuel', 'train-front', 'plane', 'bike',
  'house', 'lightbulb', 'wifi', 'smartphone', 'tv', 'wrench', 'hammer',
  'pill', 'stethoscope', 'heart', 'dumbbell', 'scissors',
  'shopping-bag', 'shirt', 'gift', 'sparkles', 'flower-2',
  'clapperboard', 'ticket', 'music', 'gamepad-2', 'book-open', 'graduation-cap',
  'repeat', 'package', 'tag', 'globe', 'tree-palm', 'umbrella',
  'baby', 'users', 'dog', 'cat', 'paw-print',
  'wallet', 'piggy-bank', 'landmark', 'credit-card', 'banknote', 'coins', 'briefcase', 'receipt',
];

const packageDir = process.argv[2];
const { version } = JSON.parse(readFileSync(join(packageDir, 'package.json'), 'utf8'));
const license = readFileSync(join(packageDir, 'LICENSE'), 'utf8').trim();

const icons = NAMES.map((name) => {
  const svg = readFileSync(join(packageDir, 'icons', `${name}.svg`), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '');
  return `  ${JSON.stringify(name)}: ${JSON.stringify(inner)},`;
});

writeFileSync(
  'docs/category-icons.js',
  `// Generated by tools/make-category-icons.js from lucide-static ${version}. Do not edit by hand.
/*
${license}
*/
export const CATEGORY_ICONS = {
${icons.join('\n')}
};
`,
);
